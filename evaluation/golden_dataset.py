"""
Golden dataset management — load, validate, and sample Q&A pairs.
The golden dataset is the ground truth for all eval runs.

Sources:
  1. Real FinanceBench Q&A pairs (ground truth from PatronusAI)
  2. Ragas-synthesized multi-hop questions (generated by scripts/generate_golden_dataset.py)
"""

import json
import logging
import random
from dataclasses import dataclass
from pathlib import Path

logger = logging.getLogger(__name__)

GOLDEN_DATASET_PATH = Path("evaluation/golden_dataset.json")


@dataclass
class GoldenItem:
    question: str
    answer: str
    company: str | None = None
    year: str | None = None
    source: str | None = None
    question_type: str = "factual"  # factual | reasoning | multi_hop


def load_golden_dataset(path: Path = GOLDEN_DATASET_PATH) -> list[GoldenItem]:
    """Load and validate the golden dataset."""
    if not path.exists():
        raise FileNotFoundError(
            f"Golden dataset not found at {path}.\n"
            "Generate it with: python scripts/generate_golden_dataset.py"
        )

    with open(path) as f:
        raw = json.load(f)

    items = []
    skipped = 0
    for row in raw:
        q = row.get("question") or row.get("input", "")
        a = row.get("answer") or row.get("ground_truth", row.get("expected_output", ""))

        if not q or not a:
            skipped += 1
            continue

        items.append(
            GoldenItem(
                question=q,
                answer=a,
                company=row.get("company"),
                year=row.get("year"),
                source=row.get("source"),
                question_type=row.get("evolution_type", "factual"),
            )
        )

    logger.info(f"Loaded {len(items)} golden items (skipped {skipped} incomplete)")
    return items


def sample_golden(n: int, stratified: bool = True, seed: int = 42) -> list[GoldenItem]:
    """
    Sample n items from the golden dataset.
    stratified=True preserves question_type distribution.
    """
    items = load_golden_dataset()
    random.seed(seed)

    if not stratified or n >= len(items):
        return random.sample(items, min(n, len(items)))

    by_type: dict[str, list[GoldenItem]] = {}
    for item in items:
        by_type.setdefault(item.question_type, []).append(item)

    sampled = []
    n_types = len(by_type)
    per_type = max(1, n // n_types)
    remainder = n

    for type_items in by_type.values():
        k = min(per_type, len(type_items), remainder)
        sampled.extend(random.sample(type_items, k))
        remainder -= k
        if remainder <= 0:
            break

    return sampled[:n]


def dataset_stats() -> dict:
    """Return summary statistics about the golden dataset."""
    items = load_golden_dataset()
    by_type: dict[str, int] = {}
    companies = set()

    for item in items:
        by_type[item.question_type] = by_type.get(item.question_type, 0) + 1
        if item.company:
            companies.add(item.company)

    return {
        "total": len(items),
        "by_type": by_type,
        "unique_companies": len(companies),
        "avg_question_length": (
            sum(len(i.question) for i in items) / len(items) if items else 0
        ),
        "avg_answer_length": (
            sum(len(i.answer) for i in items) / len(items) if items else 0
        ),
    }
